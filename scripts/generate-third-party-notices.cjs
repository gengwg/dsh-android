const crypto = require('node:crypto');
const fs = require('node:fs');

const lock = JSON.parse(fs.readFileSync('package-lock.json', 'utf8'));
const groups = new Map();
const licenseFiles = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE', 'LICENCE.md', 'COPYING', 'COPYING.md', 'COPYING.txt'];

function licenseName(manifest) {
  if (typeof manifest.license === 'string') return manifest.license;
  if (manifest.license?.type) return manifest.license.type;
  if (manifest.licenses) {
    return manifest.licenses.map(entry => entry.type).join(' OR ');
  }
  return 'UNDECLARED';
}

function people(manifest) {
  const values = [manifest.author, ...(manifest.contributors ?? []), ...(manifest.maintainers ?? [])];
  return [...new Set(values.filter(Boolean).map(entry => (
    typeof entry === 'string' ? entry : [entry.name, entry.email, entry.url].filter(Boolean).join(' ')
  )))];
}

for (const [path, metadata] of Object.entries(lock.packages)) {
  if (!path.startsWith('node_modules/') || metadata.dev) continue;
  const manifestPath = `${path}/package.json`;
  if (!fs.existsSync(manifestPath)) continue;
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const name = manifest.name || path.split('/').slice(-2).join('/');
  const version = manifest.version || metadata.version || 'unknown';
  const license = licenseName(manifest);
  const licensePath = licenseFiles.map(file => `${path}/${file}`).find(fs.existsSync);
  const text = licensePath
    ? fs.readFileSync(licensePath, 'utf8').replace(/\r\n?/g, '\n').replace(/[ \t]+$/gm, '').trim()
    : '';
  const attribution = people(manifest);
  const key = text
    ? crypto.createHash('sha256').update(text).digest('hex')
    : `${license}\0${attribution.join(', ')}`;
  if (!groups.has(key)) {
    groups.set(key, { license, text, packages: [], attribution, missingFile: !licensePath });
  }
  groups.get(key).packages.push(`${name}@${version}`);
}

const sorted = [...groups.values()].sort((left, right) => (
  left.license.localeCompare(right.license)
    || left.packages[0].localeCompare(right.packages[0])
));
const packageCount = sorted.reduce((total, group) => total + group.packages.length, 0);
const lines = [
  '# Third-party notices',
  '',
  'DSH Android depends on the following production packages. Development-only packages are excluded.',
  '',
  `This file contains ${packageCount} package attributions in ${sorted.length} groups. It is generated by \`npm run notices\`; do not edit it manually.`,
  '',
  'The DSH Android application itself is licensed under the MIT License in `LICENSE`.',
  '',
];

for (const group of sorted) {
  lines.push(`## ${group.license}`, '');
  for (const pkg of group.packages.sort()) lines.push(`- ${pkg}`);
  lines.push('');
  if (group.missingFile) {
    lines.push('The npm package does not include a standalone license file. Its package metadata declares the license shown above.');
    if (group.attribution.length > 0) {
      lines.push('', `Package author/maintainer metadata: ${group.attribution.join('; ')}`);
    }
  } else {
    lines.push('```text', group.text, '```');
  }
  lines.push('');
}

const markdown = `${lines.join('\n').trimEnd()}\n`;
fs.writeFileSync('THIRD_PARTY_NOTICES.md', markdown);
const escaped = markdown.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
fs.writeFileSync(
  'assets/third-party-notices.html',
  `<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1">\n<title>Third-party notices</title>\n</head>\n<body>\n<pre>${escaped}</pre>\n</body>\n</html>\n`,
);
console.log(`Generated notices for ${packageCount} packages in ${sorted.length} groups`);
